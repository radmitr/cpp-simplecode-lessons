// C++98 — спецификаторы доступа public, protected и private.
// C++11 — инициализаторы полей внутри класса.
#include "../../common/console.hpp"
#include <iostream>
#include <clocale>

using namespace std;

/*---------------------------
*   Модификаторы доступа
*---------------------------*/

class Point {

    //....................................
    //  Область доступа для "всех" и везде
    //....................................
public:
    int x;
    void Print()    // видны все поля
    {
        cout << " Y = " << y << "\n X = " << x << "\n Z = " << z << endl;
        PrintY();   // вызов метода из области доступа private
    }

    //..........................................................................................................
    // Область доступа только для данного класса и дружественных (friend) функций и классов (по умолчанию !!!)
    //..........................................................................................................
private:
    int z = 7;
    void PrintY()   // в функции (методе) видны все поля класса
    {
        cout << " Private-Protected PrintY(): " << y << endl;  //  y=5 из области для наследников из protected
    }

    //............................................
    // Доступ у методов самого класса и у наследников
    //............................................
protected:
    int y = 5;
};

/***********************
          MAIN
************************/
int main()
{
    console::setupConsoleEncoding();

    cout << "\n____________________________________________________________\n" << endl;

    Point a;
    a.x = 2;
    a.Print();

    return 0;
}
