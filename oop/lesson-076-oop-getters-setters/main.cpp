// C++98 — геттеры и сеттеры; C++11 — инициализаторы полей внутри класса.
#include "../../common/console.hpp"
#include <iostream>
#include <string>

using namespace std;

/*----------------------------------
 *  геттеры и сеттеры
 *  инкапсуляция
 *
 *  данные отделены от методов
 *--------------------------------*/

 // --- Getters & Setters ---
class Point {

    //-----------------------------------------
    //  Д А Н Н Ы Е: поля или свойства класса
    //-----------------------------------------
private:
    int x = 0;
    int y = 0;

public:
    int px = 0;
    int py = 0;

    int GetX()                  // GETTER ! для поля X
    {
        return this->x;         // вернуть значение "x"
    }

    //-------------------------------------
    //    С Е Т Т Е Р Ы  и  Г Е Т О Р Ы
    //-------------------------------------

        //void SetX(int valueX)     // Параметр может называться x; this->x обозначает поле объекта.
    void SetX(int x)
    {
        this->x = x;            // установить "x" (через указатель this)
    }

    int GetY()                  // GETTER ! для поля Y
    {
        return this->y;         // вернуть "y" (через указатель this)
    }

    // void SetY(int valueY)    // SETTER ! для поля Y
    void SetY(int y)
    {
        this->y = y * 2;        // установить и модифицировать y
    }

    //--------------------
    //    М Е Т О Д Ы
    //--------------------
    void Print()                // публичный метод
    {
        cout << "\n Print(): \n" << " X = " << x << "\t Y =  " << this->y << endl;
        cout << " px = " << this->px << "\t py= " << py << endl << endl;
    }
};

/***********************
      === MAIN ===
************************/
int main()
{
    console::setupConsoleEncoding();

    Point a;                    // Объект "a" класса "Point"

    a.SetX(5);                  // Установить переменную в объекте "a" класса "Point"
    a.SetY(11);
    a.Print();                  // Вывод результата

    cout << " a.GetY() = " << a.GetY() << endl;

    cout << "\n____________________________________________________________\n" << endl;

    a.px = 100;
    a.py = 200;
    a.Print();

    return 0;
}
