// C++98 — перегрузка конструкторов.
#include <iostream>

#include "../../common/console.hpp"

using namespace std;

/*------------------------------------------------------------------------
*   перегрузка конструкторов класса
*
*   Перегрузка конструктора классов очень похожа на перегрузку функций.
*
*   Перегрузка это один из видов полиморфизма,
*   когда меняется поведение объектов в зависимости от разных ситуаций.
*------------------------------------------------------------------------*/

// Constructors + Getter-Setter + Methods

class Point {

private:
    int x;
    int y;

public:

    // --- КОНСТРУКТОРЫ ---

    Point()                             // Конструктор по умолчанию (инициализация данных)
    {
        this->x = 0;
        this->y = 0;
    }

    Point(int x, int y)                 // Второй конструктор с параметрами для перегрузки
    {
        this->x = x;
        this->y = y;
    }

    Point(int valueX, bool boolean)     // Третий конструктор (bool)
    {
        this->x = valueX;

        if (boolean)
        {
            this->y = 1;
        }
        else
        {
            this->y = -1;
        }
    }

    // --- СЕТТЕРЫ И ГЕТТЕРЫ ---

    int GetX()              // GETTER ! для поля X
    {
        return this->x;     // вернуть значение "x"
    }

    void SetX(int x)        // Параметр может называться x; this->x обозначает поле объекта.
    {
        this->x = x;        // установить "x"
    }

    int GetY()              // GETTER ! для поля Y
    {
        return this->y;
    }

    void SetY(int y)        // SETTER ! для поля Y
    {
        this->y = y;
    }

    // --- МЕТОДЫ ---

    void Print()            // публичный метод
    {
        cout << " X = " << this->x << "\t Y =  " << this->y << endl << endl;
    }
};

/***********************
      === MAIN ===
************************/
int main()
{
    console::setupConsoleEncoding();

    cout << "\n____________________________________________________________\n" << endl;

    //Point a(5, 44);
    Point a;            // объект для первого конструктора (по умолчанию)
    a.Print();

    Point b(77, 9);     // объект для второго конструктора (перегрузка)
    b.Print();

    Point c(22, false); // объект для третьего конструктора (перегрузка)
    c.Print();

    return 0;
}
