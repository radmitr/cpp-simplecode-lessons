// C++98 — рекурсивный факториал и проверка границ.
#include <cstdio>
#include <iostream>

#include "../../common/console.hpp"

using namespace std;

// --- СТЕК и РЕКУРСИЯ ---
int Foo(int a)
{
    if (a < 1) return 0;    // если конец рекурсии - выйти с нулём
    a--;                    // уменьшить счётчик рекурсии

    cout << "\tfoo (recursion test): a = " << a << endl;

    return Foo(a);
}

/*---------------------------------------------------------------
* Рекурсия. Факториал.
* Факториал натурального числа N определяется как произведение
* всех натуральных чисел от 1 до N включительно
* N! = N * (N-1)!
* 1! = 1
* 0! = 1
* 2! = 2 * (2-1)!
* 5! = 1 * 2 * 3 * 4 * 5 = 120:
* (5-1)! -> 4!
* (4-1)! -> 3!
* (3-1)! -> 2!
* (2-1)! -> 1!
*---------------------------------------------------------------*/

int Fact(int N)
{
    // выход из рекурсии
    if (N == 0) return 1; // 0! = 1.
    if (N == 1) return 1;

    // рекурсия - факториал!
    return N * Fact(N - 1);
}

int main()
{
    console::setupConsoleEncoding();

    puts("-------------------------------");
    cout << "  Р е к у р с и я \"ФАКТОРИАЛ\" " << endl;
    puts("-------------------------------\n");

    // функция с рекурсией
    // Пять шагов с выводом, затем базовый вызов Foo(0).
    Foo(5);
    cout << endl;

    // Факториал
    int Num;
    cout << "\tФАКТОРИАЛ (!): ";
    if (!(cin >> Num) || Num < 0 || Num > 12)
    {
        cerr << "Expected integer in [0, 12]\n";
        return 1;
    }
    cout << " Result: " << Fact(Num) << endl << endl;

    return 0;
}
